// Operadores de comparação
// >, <, >=, <=, ==, ===, !=, !==

// Maior que
console.log(10 > 5); // true

// Menor que
console.log(10 < 5); // false

// Maior ou igual a
console.log(10 >= 10); // true

// Menor ou igual a
console.log(10 <= 5); // false

// Igual a (valor)
console.log(10 == '10'); // true

// Igual a (valor e tipo)
console.log(10 === '10'); // false

// Diferente de (valor)
console.log(10 != '10'); // false

// Diferente de (valor e tipo)
console.log(10 !== '10'); // true