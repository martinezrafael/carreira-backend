// Legibilidade de variáveis em JavaScript

let x = 1.89; // Variável com nome pouco descritivo
let alturadoRafael = 1.89; // Variável com nome mais descritivo

// case sensitive
let nome = "Rafael";
let Nome = "João";

console.log(nome); // Saída: Rafael
console.log(Nome); // Saída: João

// camelCase
let alturaDoRafael = 1.89; // Nome de variável em camelCase

// snake_case
let altura_do_rafael = 1.89; // Nome de variável em snake_case

// PascalCase
let AlturaDoRafael = 1.89; // Nome de variável em PascalCase

// kebab-case (não é permitido em variáveis JavaScript)
// let altura-do-rafael = 1.89; // Isso geraria um erro de sintaxe

// Boas práticas de legibilidade
let idadeDoUsuario = 25; // Nome de variável descritivo e legível
let numeroDeItens = 10; // Nome de variável descritivo e legível

// Evitar abreviações excessivas
let qtdItens = 10; // Nome de variável pouco descritivo
let quantidadeDeItens = 10; // Nome de variável mais descritivo

// Evitar nomes genéricos
let data = "2024-06-01"; // Nome de variável genérico
let dataDeNascimento = "2024-06-01"; // Nome de variável mais específico
